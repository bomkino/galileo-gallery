const assert = require("node:assert/strict")
const crypto = require("node:crypto")
const fs = require("node:fs")
const path = require("node:path")
const AdmZip = require("adm-zip")

const root = path.resolve(process.argv[2] || "artifacts/g05")
const projectPath = path.resolve(process.argv[3] || path.join(root, "round-trip.galileo"))
const receipts = ["save", "reopen"].map((mode) => JSON.parse(fs.readFileSync(path.join(root, `renderer-${mode}.json`), "utf8")))
for (const [index, receipt] of receipts.entries()) {
    assert.equal(receipt.schema, "galileo-gallery-g05-renderer-receipt-v1")
    assert.equal(receipt.journey.mode, index === 0 ? "save" : "reopen")
    assert.equal(receipt.journey.audioLaneCount, 2)
    assert.deepEqual(receipt.journey.lanes.map((lane) => lane.role).sort(), ["presenter", "soundtrack"])
    assert(receipt.journey.lanes.every((lane) => lane.waveformBuckets === 48))
    assert.equal(receipt.journey.lanes.find((lane) => lane.role === "soundtrack").gain, 0.6)
    assert.equal(receipt.journey.ducking, true)
    assert.match(receipt.journey.diagnostic, /^Checked \d+ frames · peak \d+\.\d{3} · clipped \d+$/)
    assert.match(receipt.journey.diagnosticHash, /^[a-f0-9]{64}$/)
    assert.equal(receipt.journey.rawPathVisible, false)
    assert.equal(receipt.journey.grantInDataset, false)
    assert.equal(receipt.journey.identity.sourceSha, process.env.G05_EXPECTED_SHA)
    assert.equal(receipt.journey.identity.sourceTree, process.env.G05_EXPECTED_TREE)
    assert(receipt.capture.bytes > 10_000)
}
assert.equal(receipts[0].journey.diagnostic, receipts[1].journey.diagnostic)
assert.equal(receipts[0].journey.diagnosticHash, receipts[1].journey.diagnosticHash)
assert(fs.statSync(projectPath).size > 1_000)
const manifest = JSON.parse(new AdmZip(projectPath).readAsText("project/project.json"))
const presenter = manifest.audio.lanes.find((lane) => lane.role === "presenter")
const soundtrack = manifest.audio.lanes.find((lane) => lane.role === "soundtrack")
assert.deepEqual(presenter.clips[0].timelineStart, { denominator: 1, numerator: 1 })
assert.deepEqual(soundtrack.clips[0].timelineStart, { denominator: 1, numerator: 0 })
assert.equal(soundtrack.gain, 0.6)
assert.equal(manifest.audio.ducking.enabled, true)
assert.equal(JSON.stringify(manifest).includes("reel-media://"), false)
const projectSha256 = crypto.createHash("sha256").update(fs.readFileSync(projectPath)).digest("hex")
assert.match(projectSha256, /^[a-f0-9]{64}$/)
console.log(`Verified: G05 packaged HostPort audio authoring, waveform, PCM diagnostic, controls, ducking, path privacy, and exact save/reopen (${projectSha256}).`)
