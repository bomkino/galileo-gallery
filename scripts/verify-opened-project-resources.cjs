fs.writeFileSync(path.join(root, "artifact-manifest.json"), `${JSON.stringify({ format: "galileo-gallery-shelf-artifacts", version: 1, files: rows, aggregateSha256: sha256(JSON.stringify(rows)) }, null, 2)}\n`)
