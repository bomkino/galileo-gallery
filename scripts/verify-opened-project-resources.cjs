const rows = []
const walk = (directory, relative = "") => {
    for (const entry of fs.readdirSync(directory, { withFileTypes: true }).sort((left, right) => left.name.localeCompare(right.name))) {
        if (entry.name === "artifact-manifest.json") continue
        const target = path.join(directory, entry.name)
        const name = relative ? `${relative}/${entry.name}` : entry.name
        const linked = fs.lstatSync(target)
        assert.equal(linked.isSymbolicLink(), false, "Shelf artifact contains a symbolic link")
        if (entry.isDirectory()) walk(target, name)
        else if (entry.isFile()) {
            const bytes = fs.readFileSync(target)
            rows.push({ file: name, bytes: bytes.length, sha256: sha256(bytes) })
        } else assert.fail("Shelf artifact contains a special file")
    }
}
walk(root)
