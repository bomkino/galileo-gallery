const assert = require("node:assert/strict")
const crypto = require("node:crypto")
const fs = require("node:fs")
const path = require("node:path")
const { spawnSync } = require("node:child_process")
const approved = require("./ffmpeg-approved-binaries.json")

const packaged = path.resolve(process.argv[2] || "release/g03/linux-unpacked/resources/ffmpeg/ffmpeg")
const pinned = require("ffmpeg-static")
assert(pinned && fs.existsSync(pinned), "The package-lock-pinned FFmpeg binary is missing.")
assert(fs.existsSync(packaged), "The packaged FFmpeg binary is missing.")
const digest = (filePath) => crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex")
const target = `${process.platform}-${process.arch}`
assert.equal(digest(pinned), approved.sha256[target], `Installed FFmpeg does not match approved ${approved.release} identity.`)
assert.equal(digest(packaged), digest(pinned), "Packaged FFmpeg differs from the package-lock-pinned binary.")
if (process.platform !== "win32") assert.notEqual(fs.statSync(packaged).mode & 0o111, 0, "Packaged FFmpeg is not executable.")
const version = spawnSync(packaged, ["-version"], { encoding: "utf8", env: { LANG: "C", LC_ALL: "C", PATH: "/usr/bin:/bin" } })
assert.equal(version.status, 0)
assert.match(version.stdout, new RegExp(`^ffmpeg version ${approved.version.replaceAll(".", "\\.")} `))
console.log(`Verified: packaged FFmpeg is executable and byte-identical to approved ${approved.release}/${approved.version} (${digest(packaged)}).`)
