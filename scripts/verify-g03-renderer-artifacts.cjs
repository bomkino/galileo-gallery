const assert = require("node:assert/strict")
const crypto = require("node:crypto")
const fs = require("node:fs")
const path = require("node:path")

const root = path.resolve(process.argv[2] || "artifacts/g03")
const project = path.resolve(process.argv[3] || path.join(root, "round-trip.galileo"))
const hash = (filePath) => crypto.createHash("sha256").update(fs.readFileSync(filePath)).digest("hex")
const receipts = ["save", "reopen"].map((mode) => JSON.parse(fs.readFileSync(path.join(root, `renderer-${mode}.json`), "utf8")))

for (const [index, receipt] of receipts.entries()) {
    const mode = index === 0 ? "save" : "reopen"
    assert.equal(receipt.schema, "galileo-gallery-g03-renderer-receipt-v1")
    assert.equal(receipt.platform, "linux")
    assert.equal(receipt.journey.mode, mode)
    assert.equal(receipt.journey.identity.productId, "galileo-gallery")
    assert.equal(receipt.journey.identity.protocol, 1)
    assert.equal(receipt.journey.identity.packaged, true)
    assert.equal(receipt.journey.identity.sourceSha, process.env.G03_EXPECTED_SHA)
    assert.equal(receipt.journey.identity.sourceTree, process.env.G03_EXPECTED_TREE)
    assert.match(receipt.journey.identity.buildId, /^g03-/)
    assert.equal(receipt.journey.frameCount, 1)
    assert.equal(receipt.journey.canvas, "1080x1920")
    assert.equal(receipt.journey.axis, "vertical")
    assert(receipt.journey.mediaURLs.every((url) => /^reel-media:\/\/grant\/[a-f0-9]{64}$/.test(url)))
    assert.equal(receipt.journey.rawPathVisible, false)
    assert.deepEqual(receipt.journey.nodeAccess, { process: "undefined", require: "undefined" })
    assert.equal(receipt.journey.popupDenied, true)
    assert.equal(receipt.journey.remoteFetchBlocked, true)
    assert.equal(receipt.journey.rawMediaBlocked, true)
    assert.equal(receipt.journey.permissionState, "denied")
    assert(receipt.journey.identity.securityDecisions["popup-denied"] >= 1)
    assert(receipt.journey.identity.securityDecisions["navigation-denied"] >= 1)
    assert(receipt.journey.identity.securityDecisions["permission-denied"] >= 1)
    assert(receipt.journey.identity.securityDecisions["download-denied"] >= 1)
    assert(receipt.journey.identity.securityDecisions["request-denied"] >= 1)
    assert.match(receipt.journey.location, /^gallery-app:\/\/app\/index\.html\?tracer=quiet-carousel&host=linux$/)
    const target = path.join(root, receipt.capture.file)
    assert(fs.statSync(target).size > 10_000)
    assert.equal(hash(target), receipt.capture.sha256)
}
assert(fs.statSync(project).size > 1_000)
const evidenceText = receipts.map((receipt) => JSON.stringify(receipt)).join("\n")
assert.equal(evidenceText.includes(project), false)
console.log("Verified: G03 real Electron opaque media import, portable save/relaunch/reopen, strict origin, frozen bridge, popup/network/raw-media denial, screenshots, and path-free evidence.")
